export function applyAuthoredWorklogCopy(entry) {
  const copy = WORKLOG_PUBLIC_COPY[entry.id];
  if (!copy) return entry;
  return {
    ...entry,
    ...copy,
    impact: copy.impact ? { ...entry.impact, ...copy.impact } : entry.impact
  };
}

function authored({ title, summary, used, changed }) {
  const impact = {};
  if (used) impact.used = used;
  if (changed) impact.changed = changed;
  return {
    ...(title && { title }),
    ...(summary && { summary }),
    ...(Object.keys(impact).length > 0 && { impact })
  };
}
